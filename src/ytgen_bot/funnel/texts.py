def _goal_phrase(goal: str | None, kb: KnowledgeBase) -> str:
    return {
        "n1_more": "Ты хочешь выпускать больше видео за то же время, а сборка тут идёт автоматически.",
        "n1_scale": f"Ты хочешь запускать ещё каналы, а {_lower_first(kb.fact('channels'))}",
        "n1_start": "Ты стартуешь с нуля, а настройка канала занимает несколько кликов.",
        "n1_time": "Ты хочешь освободить время для тем и стратегии, а рутину берёт на себя софт.",
        "n1_lang": f"Ты хочешь выйти на другие языки, а {kb.fact('dubbing_goal_clause')}.",
    }.get(goal or "", "")


def _lower_first(text: str) -> str:
    return text[:1].lower() + text[1:]


def recommendation(tariff: FunnelTariff, goal: str | None, kb: KnowledgeBase) -> str:
    parts = [f"Судя по твоим ответам, тебе подойдёт <b>{esc(tariff.name)}</b>."]
    phrase = _goal_phrase(goal, kb)
    if phrase:
        parts.append(phrase)
    parts.append(f"{render.limits_phrase(tariff)}")
    return (
        " ".join(parts)
        + f"\n\n{render.price_period(tariff)}. Автопродления нет: продлевать или нет, решаешь сам."
    )


