def support_url(contact: str) -> str | None:
    """`https://t.me/<handle>` built from SUPPORT_CONTACT; None when it is not a plain @handle (no URL button then)."""
    match = _HANDLE_RE.fullmatch(contact.strip())
    return f"https://t.me/{match.group(1)}" if match else None


